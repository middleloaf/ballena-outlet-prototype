function normalize(value) {
  return String(value ?? "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const escapeRe = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// Longest keys first so "shower curtain rod" is not shadowed by "shower".
const SORTED_TERMS = TERM_ALIASES.map(([key, aliases]) => ({
  key: normalize(key),
  aliases,
})).sort((a, b) => b.key.length - a.key.length);

function hasTerm(text, key) {
  if (!key) return false;
  // Match the plural only when it is plausible: "mat" must not match "mates".
  const plural = /(?:s|x|z|ch|sh)$/.test(key) ? "(?:es|s)?" : /y$/.test(key) ? "(?:ies|s)?" : "s?";
  const re = new RegExp(`(?:^|\\s)${escapeRe(key)}${plural}(?=\\s|$)`, "i");
  return re.test(text);
}

/**
 * Build a search-only Spanish alias string for an item.
 *
 * @param {object} input
 * @param {string[]} input.names English and/or Spanish names to inspect.
 * @param {string} input.category Category slug.
 * @param {string|string[]} [input.manual] Optional aliases from a buscar_es column.
 * @returns {string} Comma-separated aliases, or "" when nothing matched.
 */
export function spanishSearchTerms({ names = [], category = "otros", manual = "" } = {}) {
  const aliases = [];
  const seen = new Set();
  const add = (value) => {
    const text = String(value ?? "").trim().replace(/\s+/g, " ");
    if (!text) return;
    const key = normalize(text);
    if (!key || seen.has(key)) return;
    seen.add(key);
    aliases.push(text);
  };

  const manualList = Array.isArray(manual) ? manual : String(manual ?? "").split(/[,;|\n]+/);
  for (const value of manualList) add(value);

  for (const value of CATEGORY_ALIASES[category] || CATEGORY_ALIASES.otros) add(value);

  const text = normalize(names.filter(Boolean).join(" "));
  if (text) {
    for (const term of SORTED_TERMS) {
      const scope = CATEGORY_SCOPES[term.key];
      if (scope && !scope.includes(category)) continue;
      if (!hasTerm(text, term.key)) continue;
      for (const alias of term.aliases) add(alias);
    }
  }

  return aliases.join(", ").slice(0, 1200);
}
